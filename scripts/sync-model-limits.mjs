/**
 * Regenerate src/model-limits.generated.ts from models.dev.
 *
 * Z.ai's own API exposes no per-model context window: GET /models/{id} returns
 * only {id, object, created, owned_by}. models.dev aggregates provider metadata
 * including limit.context / limit.output and modalities.input, which is what this
 * file carries.
 *
 * Usage: node scripts/sync-model-limits.mjs
 * Review the diff before committing — it rewrites the whole table.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE_URL = 'https://models.dev/api.json';
const PROVIDER = 'zai';
const FALLBACK_PROVIDER = 'zhipuai';

const { default: got } = await import('got');

const catalog = await got(SOURCE_URL, { timeout: { request: 60_000 }, retry: { limit: 2 } }).json();

const providers = [catalog[PROVIDER], catalog[FALLBACK_PROVIDER]].filter(Boolean);
if (providers.length === 0) {
  throw new Error(`models.dev has no "${PROVIDER}" provider; keys sample: ${Object.keys(catalog).slice(0, 10)}`);
}

/** Merge provider entries, preferring the first provider that knows the model. */
const models = new Map();
for (const provider of providers) {
  for (const [id, model] of Object.entries(provider.models ?? {})) {
    if (!models.has(id)) models.set(id, model);
  }
}

const entries = [...models.entries()]
  .map(([id, model]) => ({
    id,
    maxInputTokens: model.limit?.context,
    maxOutputTokens: model.limit?.output,
    vision: Array.isArray(model.modalities?.input) && model.modalities.input.includes('image'),
    toolCalling: model.tool_call === true,
  }))
  .filter(entry => typeof entry.maxInputTokens === 'number' && entry.maxInputTokens > 0)
  .sort((a, b) => a.id.localeCompare(b.id));

if (entries.length === 0) {
  throw new Error('models.dev returned no usable model limits');
}

const body = entries
  .map(entry =>
    [
      `  '${entry.id}': { maxInputTokens: ${entry.maxInputTokens}, maxOutputTokens: ${entry.maxOutputTokens} },`,
      `    // capabilities: vision=${entry.vision} toolCalling=${entry.toolCalling}`,
    ].join('\n'),
  )
  .join('\n');

const visionBody = entries
  .filter(entry => entry.vision)
  .map(entry => `  '${entry.id}',`)
  .join('\n');

const contents = `// AUTO-GENERATED by scripts/sync-model-limits.mjs — do not edit by hand.
// Source: ${SOURCE_URL} (provider "${PROVIDER}", fallback "${FALLBACK_PROVIDER}").
// Verified: ${new Date().toISOString().slice(0, 10)}
//
// Z.ai's API returns no context window, so this table is the source of truth for
// context sizing. Regenerate with \`pnpm run models:sync\`.

export interface ModelCapabilityEntry {
  maxInputTokens: number;
  maxOutputTokens?: number;
}

export const MODEL_TOKEN_LIMITS: Record<string, ModelCapabilityEntry> = {
${body}
};

/** Models that accept image input, per models.dev modalities.input. */
export const VISION_MODEL_IDS: ReadonlySet<string> = new Set([
${visionBody}
]);
`;

mkdirSync(resolve(ROOT, 'src'), { recursive: true });
writeFileSync(resolve(ROOT, 'src', 'model-limits.generated.ts'), contents, 'utf8');

console.log(`Wrote ${entries.length} model entries to src/model-limits.generated.ts`);
console.log(`  vision-capable: ${entries.filter(e => e.vision).map(e => e.id).join(', ') || '(none)'}`);